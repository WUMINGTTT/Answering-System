/**
 * 【文件说明】得分记录类型定义
 *
 * 本文件定义了答题系统中得分记录相关的 TypeScript 类型
 * 包括：得分详情接口、创建得分的类型
 *
 * 【技术学习】得分记录的设计思路
 *
 * 1. 为什么需要得分记录？
 *    - 记录每次得分的详细信息，便于追溯和审计
 *    - 支持查看得分历史，了解得分来源
 *    - 便于统计分析，如平均分、最高分等
 *
 * 2. 得分记录包含哪些信息？
 *    - 唯一标识：用于区分不同的得分记录
 *    - 得分分值：具体的分数（可以是正数或负数）
 *    - 得分原因：说明为什么得到这个分数
 *    - 创建时间：记录得分的时间戳
 *
 * 3. 为什么使用时间戳而不是日期字符串？
 *    - 时间戳是数字类型，便于排序和计算时间差
 *    - 占用存储空间小
 *    - 时区无关，避免时区转换问题
 *    - 前端可以方便地转换为本地时间显示
 */

/**
 * 得分详情接口：定义单次得分记录的数据结构
 *
 * 每次得分都会创建一条记录，记录得分的详细信息
 * 这些记录会被存储在用户的 scoreDetails 数组中
 */
export interface ScoreDetail {
  /** 得分记录唯一标识符，使用 nanoid 生成 */
  id: string;

  /**
   * 得分分值
   * 正数表示加分，负数表示扣分
   * 示例：10（答对加10分）、-5（答错扣5分）
   */
  score: number;

  /**
   * 得分原因：说明为什么得到这个分数
   * 示例：
   * - "答对必答题第1题"
   * - "抢答成功，答对抢答题"
   * - "风险题答错，扣除相应分数"
   */
  reason: string;

  /**
   * 创建时间：Unix 时间戳（毫秒）
   * 使用 Date.now() 获取，表示从 1970-01-01 00:00:00 UTC 到现在的毫秒数
   *
   * 【技术学习】Unix 时间戳
   * - 是一种时间表示方式，表示从 1970-01-01 00:00:00 UTC 起经过的秒数
   * - 毫秒级时间戳 = 秒级时间戳 × 1000
   * - JavaScript 中 Date.now() 返回毫秒级时间戳
   * - 可以通过 new Date(timestamp) 转换为 Date 对象
   */
  createdAt: number;
}

/**
 * 【技术学习】创建得分的类型设计
 *
 * 使用 Pick 从 ScoreDetail 中选取需要的属性：
 * - score：得分分值（必填）
 * - reason：得分原因（必填）
 *
 * 不包含的属性：
 * - id：由后端自动生成（使用 nanoid）
 * - createdAt：由后端自动生成（使用 Date.now()）
 *
 * 这种设计的好处：
 * 1. 简化前端调用：只需提供业务相关的字段
 * 2. 数据一致性：id 和时间戳由后端统一生成
 * 3. 安全性：防止前端篡改 id 或时间
 */
export type CreateScore = Pick<ScoreDetail, 'score' | 'reason'>;
